// Idioma de la landing: inglés por defecto, español opcional.
// Misma clave que la app: localStorage 'xpaze-lang' ('en' | 'es'); ?lang=es|en la fuerza.
// El HTML se sirve en inglés; los elementos con data-i18n (y data-i18n-aria-label / -alt)
// se rellenan desde DICT al arrancar. Cambiar de idioma guarda la elección y recarga
// conservando la posición, así cada módulo (Paze, chequeo, clima espacial…) nace ya en su idioma.

const KEY = 'xpaze-lang';

function detect() {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q === 'es' || q === 'en') { localStorage.setItem(KEY, q); return q; }
    const s = localStorage.getItem(KEY);
    if (s === 'es' || s === 'en') return s;
  } catch { /* sin almacenamiento */ }
  return 'en';
}

const current = detect();
export const lang = () => current;
export const locale = () => (current === 'es' ? 'es-ES' : 'en-GB');

/** Número con los decimales indicados según el idioma: 11.0 / 11,0. */
export const num = (v, d = 0) => v.toLocaleString(locale(), { minimumFractionDigits: d, maximumFractionDigits: d });

/** Texto por clave, con {variables}. Si falta en un idioma, cae al inglés y luego a la clave. */
export function t(key, vars) {
  let s = DICT[current][key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function setLang(l) {
  if ((l !== 'en' && l !== 'es') || l === current) return;
  try {
    localStorage.setItem(KEY, l);
    sessionStorage.setItem('xpaze-lang-scroll', String(window.scrollY));
  } catch { /* sin almacenamiento */ }
  const u = new URL(location.href);
  u.searchParams.delete('lang');
  if (u.href === location.href) location.reload();
  else location.replace(u.href);
}

/** Aplica el idioma al documento (textos, atributos, <title>, meta) y conecta el selector. */
export function initI18n(doc = document) {
  const root = doc.documentElement;
  root.lang = current;
  if (current !== 'en') {
    const d = DICT[current];
    doc.querySelectorAll('[data-i18n]').forEach((el) => { const v = d[el.dataset.i18n]; if (v != null) el.innerHTML = v; });
    for (const attr of ['aria-label', 'alt', 'title']) {
      doc.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => { const v = d[el.getAttribute(`data-i18n-${attr}`)]; if (v != null) el.setAttribute(attr, v); });
    }
  }
  doc.title = t('meta.title');
  const meta = (sel, key) => doc.querySelector(sel)?.setAttribute('content', t(key));
  meta('meta[name="description"]', 'meta.description');
  meta('meta[property="og:title"]', 'meta.ogTitle');
  meta('meta[property="og:description"]', 'meta.ogDescription');
  meta('meta[property="og:locale"]', current === 'es' ? 'meta.ogLocaleEs' : 'meta.ogLocaleEn');
  meta('meta[property="og:locale:alternate"]', current === 'es' ? 'meta.ogLocaleEn' : 'meta.ogLocaleEs');

  doc.querySelectorAll('.lang [data-lang]').forEach((b) => {
    const on = b.dataset.lang === current;
    b.setAttribute('aria-pressed', String(on));
    b.setAttribute('aria-label', on ? b.textContent : t('lang.switch', { name: b.title }));
    b.addEventListener('click', () => setLang(b.dataset.lang));
  });

  root.classList.remove('i18n-wait');

  // tras un cambio de idioma, vuelve a donde estaba (cuando el diseño ya está montado)
  let y = null;
  try { y = sessionStorage.getItem('xpaze-lang-scroll'); sessionStorage.removeItem('xpaze-lang-scroll'); } catch { /* nada */ }
  return y == null ? null : Number(y);
}

